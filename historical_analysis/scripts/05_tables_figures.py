#!/usr/bin/env python3
"""Phase 5: emit LaTeX number-macros, tables, and figures from metrics JSON.

Three reviewer models (7B / 14B / 32B Qwen2.5-Coder), naive vs calibrated, Lite + Verified.

Usage:  python scripts/05_tables_figures.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REP = ROOT / "results" / "reports"
TAB = ROOT / "results" / "tables"
FIG = ROOT / "results" / "figures"
PAPER = ROOT / "paper"

MODELS = [("7B", "reviewer-7b", "reviewer-7b-cal"),
          ("14B", "reviewer-14b", "reviewer-14b-cal"),
          ("32B", "reviewer-32b", "reviewer-32b-cal")]
TAX_NAMES = {
    "F1": "Functional incompleteness", "F2": "Regression risk", "F3": "Test overfitting",
    "F4": "Non-minimal change", "F5": "Maintainability", "F6": "Convention mismatch",
    "F7": "Insufficient tests", "F8": "Fragile approach", "F9": "API/compat break",
    "F10": "Performance", "F11": "Doc/comment gap",
}


def load(rev: str):
    p = REP / f"metrics_{rev}.json"
    return json.loads(p.read_text()) if p.exists() else None


def macro(name, val):
    return f"\\newcommand{{\\{name}}}{{{val}}}\n"


def main() -> int:
    for d in (TAB, FIG, PAPER):
        d.mkdir(parents=True, exist_ok=True)

    strict = {sz: load(s) for sz, s, c in MODELS}
    cal = {sz: load(c) for sz, s, c in MODELS}
    agree = json.loads((REP / "agreement.json").read_text()) if (REP / "agreement.json").exists() else None

    # ---- number macros (primary = 14B; plus per-model false-rej) ----
    m = "% auto-generated by 05_tables_figures.py\n"
    base = cal["14B"] or strict["14B"]
    for split in ("lite", "verified"):
        cap = split.capitalize()
        S, C = strict["14B"][split], cal["14B"][split]
        m += macro(f"pctResolved{cap}", S["pct_resolved"])
        m += macro(f"nResolved{cap}", S["n_resolved"])
        m += macro(f"nTotal{cap}", S["n_total"])
        m += macro(f"strictRAP{cap}", S["RAP"])
        m += macro(f"strictFalseRej{cap}", S["gold_false_rejection_rate"])
        m += macro(f"strictGap{cap}", S["Resolution_Mergeability_Gap"])
        m += macro(f"strictMcNemar{cap}", S["mcnemar"]["p_value"])
        m += macro(f"calRAP{cap}", C["RAP"])
        m += macro(f"calRAPlo{cap}", C["RAP_ci"][0])
        m += macro(f"calRAPhi{cap}", C["RAP_ci"][1])
        m += macro(f"calMRR{cap}", C["MRR"])
        m += macro(f"calGap{cap}", C["Resolution_Mergeability_Gap"])
        m += macro(f"calGoldMerge{cap}", C["gold_mergeable_rate"])
        m += macro(f"calFalseRej{cap}", C["gold_false_rejection_rate"])
        m += macro(f"calMcNemar{cap}", C["mcnemar"]["p_value"])
        m += macro(f"calHalluc{cap}", C["hallucinated_review_rate"])
        # per-model false-rejection (naive & calibrated). LaTeX command names are
        # letters-only, so map sizes to word tokens.
        SZTOK = {"7B": "Seven", "14B": "Fourteen", "32B": "ThirtyTwo"}
        for sz, tok in SZTOK.items():
            if strict[sz]:
                m += macro(f"strict{tok}FalseRej{cap}", strict[sz][split]["gold_false_rejection_rate"])
            if cal[sz]:
                m += macro(f"cal{tok}FalseRej{cap}", cal[sz][split]["gold_false_rejection_rate"])
                m += macro(f"cal{tok}McNemar{cap}", cal[sz][split]["mcnemar"]["p_value"])
                m += macro(f"cal{tok}RAP{cap}", cal[sz][split]["RAP"])
    if agree:
        for split in ("lite", "verified"):
            m += macro(f"fleissAll{split.capitalize()}", agree[split]["fleiss_all"])
            m += macro(f"fleissAgent{split.capitalize()}", agree[split]["fleiss_agent"])
    (PAPER / "numbers.tex").write_text(m)

    # ---- Table 1: main, 3 models x 2 modes x 2 splits ----
    t = [r"\begin{tabular}{llcccccc}", r"\toprule",
         r"Model & Setting & Split & \%Resolved & RAP & Gold-acc.\% & FalseRej\% & McNemar $p$ \\",
         r"\midrule"]
    for sz, s, c in MODELS:
        for setting, key in (("Naive", strict), ("Calib.", cal)):
            d = key[sz]
            if not d:
                continue
            for split, cap in (("lite", "Lite"), ("verified", "Verified")):
                r = d[split]
                t.append(f"{sz} & {setting} & {cap} & {r['pct_resolved']} & {r['RAP']} & "
                         f"{r['gold_mergeable_rate']} & {r['gold_false_rejection_rate']} & "
                         f"{r['mcnemar']['p_value']} \\\\")
        t.append(r"\midrule")
    t[-1] = r"\bottomrule"
    t.append(r"\end{tabular}")
    (TAB / "main_table.tex").write_text("\n".join(t) + "\n")

    # ---- Table 2: reviewer quality on gold control (calibrated) ----
    q = [r"\begin{tabular}{llccc}", r"\toprule",
         r"Model & Split & Gold decision acc.\% & Hallucinated-review\% & FalseRej\% \\",
         r"\midrule"]
    for sz, s, c in MODELS:
        if not cal[sz]:
            continue
        for split, cap in (("lite", "Lite"), ("verified", "Verified")):
            r = cal[sz][split]
            q.append(f"{sz} & {cap} & {r['gold_decision_accuracy']} & "
                     f"{r['hallucinated_review_rate']} & {r['gold_false_rejection_rate']} \\\\")
    q += [r"\bottomrule", r"\end{tabular}"]
    (TAB / "quality_table.tex").write_text("\n".join(q) + "\n")

    # ---- Table 3: cross-model agreement ----
    if agree:
        a = [r"\begin{tabular}{lccc}", r"\toprule",
             r"Split & Fleiss $\kappa$ (all) & $\kappa$ (agent) & $\kappa$ (gold) \\",
             r"\midrule"]
        for split, cap in (("lite", "Lite"), ("verified", "Verified")):
            r = agree[split]
            a.append(f"{cap} & {r['fleiss_all']} & {r['fleiss_agent']} & {r['fleiss_gold']} \\\\")
        a += [r"\bottomrule", r"\end{tabular}"]
        (TAB / "agreement_table.tex").write_text("\n".join(a) + "\n")

    # ---- Table: cross-family reviewers (verified) ----
    FAMILY = [("Qwen2.5-Coder-7B", "reviewer-7b", "reviewer-7b-cal"),
              ("Qwen2.5-Coder-14B", "reviewer-14b", "reviewer-14b-cal"),
              ("Qwen2.5-Coder-32B", "reviewer-32b", "reviewer-32b-cal"),
              ("Llama-3.1-8B", "reviewer-llama8b", "reviewer-llama8b-cal"),
              ("DeepSeek-Coder-6.7B", "reviewer-dscoder", "reviewer-dscoder-cal")]
    fl = [r"\begin{tabular}{lccccc}", r"\toprule",
          r"Reviewer (family) & Naive FalseRej\% & Cal.\ FalseRej\% & Cal.\ RAP\% & Cal.\ Gold\% & McNemar $p$ \\",
          r"\midrule"]
    for name, s, c in FAMILY:
        S, C = load(s), load(c)
        if not C:
            continue
        sv = S["verified"] if S else None
        cv = C["verified"]
        nf = sv["gold_false_rejection_rate"] if sv else "--"
        fl.append(f"{name} & {nf} & {cv['gold_false_rejection_rate']} & {cv['RAP']} & "
                  f"{cv['gold_mergeable_rate']} & {cv['mcnemar']['p_value']} \\\\")
    fl += [r"\bottomrule", r"\end{tabular}"]
    (TAB / "family_table.tex").write_text("\n".join(fl) + "\n")

    # ---- Table 4: taxonomy (calibrated 14B) ----
    tx = [r"\begin{tabular}{llcc}", r"\toprule",
          r"Code & Failure mode & Lite & Verified \\", r"\midrule"]
    for f in [f"F{i}" for i in range(1, 12)]:
        l = cal["14B"]["lite"]["failure_taxonomy_any"].get(f, 0)
        v = cal["14B"]["verified"]["failure_taxonomy_any"].get(f, 0)
        if l or v:
            tx.append(f"{f} & {TAX_NAMES[f]} & {l} & {v} \\\\")
    tx += [r"\bottomrule", r"\end{tabular}"]
    (TAB / "taxonomy_table.tex").write_text("\n".join(tx) + "\n")

    # ---- figures ----
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        sizes = [sz for sz, s, c in MODELS if strict[sz] and cal[sz]]
        # fig1: gold false-rejection, naive vs cal, per model (Lite)
        fig, ax = plt.subplots(figsize=(4.6, 2.9))
        x = range(len(sizes)); w = 0.38
        nv = [strict[sz]["lite"]["gold_false_rejection_rate"] for sz in sizes]
        cv = [cal[sz]["lite"]["gold_false_rejection_rate"] for sz in sizes]
        ax.bar([i - w/2 for i in x], nv, w, label="Naive", color="#c0392b")
        ax.bar([i + w/2 for i in x], cv, w, label="Calibrated", color="#2980b9")
        ax.set_xticks(list(x)); ax.set_xticklabels(sizes)
        ax.set_ylabel("Gold false-rejection (\\%)"); ax.set_ylim(0, 100)
        ax.set_xlabel("Reviewer model size"); ax.legend(fontsize=8)
        ax.set_title("Naive reviewers reject merged code at every scale", fontsize=9)
        fig.tight_layout(); fig.savefig(FIG / "false_rejection.pdf")

        # fig2: agent vs gold acceptance, calibrated, per model (Lite)
        fig2, ax2 = plt.subplots(figsize=(4.6, 2.9))
        ag = [cal[sz]["lite"]["RAP"] for sz in sizes]
        go = [cal[sz]["lite"]["gold_mergeable_rate"] for sz in sizes]
        ax2.bar([i - w/2 for i in x], ag, w, label="Agent", color="#27ae60")
        ax2.bar([i + w/2 for i in x], go, w, label="Gold (merged)", color="#8e44ad")
        ax2.set_xticks(list(x)); ax2.set_xticklabels(sizes)
        ax2.set_ylabel("Acceptance rate (\\%)"); ax2.set_ylim(0, 100)
        ax2.set_xlabel("Reviewer model size"); ax2.legend(fontsize=8)
        ax2.set_title("Calibrated: agent $\\approx$ gold at every scale", fontsize=9)
        fig2.tight_layout(); fig2.savefig(FIG / "agent_vs_gold.pdf")
        print("wrote figures")
    except Exception as e:  # noqa: BLE001
        print(f"figure skipped: {e!r}")

    print("wrote numbers.tex + 4 tables")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
